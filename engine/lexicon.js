const original = seed.trim().split('\n').map(line => {
  const [text, aliases, nominal, vetted] = line.split('|');
  return { text, spellings: [...new Set(aliases.split(','))], nominal: nominal === 'n', vettedAlternatives:vetted==='v' };
});
const merged = new Map(original.map(entry=>[entry.text,entry]));
for (const entry of additions) {
  const existing=merged.get(entry.text);
  if(existing) {
    existing.spellings=[...new Set([...existing.spellings,...entry.spellings])];
    existing.nominal ||= entry.nominal;
  } else merged.set(entry.text,{...entry,spellings:[...entry.spellings]});
}
export const lexicon=[...merged.values()];
